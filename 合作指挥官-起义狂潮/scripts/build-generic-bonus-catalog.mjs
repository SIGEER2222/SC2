// build-generic-bonus-catalog.mjs
// Read Shared/GenericBonuses.json and generate LibE0EAE146_GenericBonusCatalog.galaxy.
// This galaxy module provides data-driven bonus->upgrade mapping, replacing the
// hardcoded upgrade lists in LibE0EAE146.galaxy GenericBonusApplyPassives().
//
// Usage: node scripts/build-generic-bonus-catalog.mjs

import { readFileSync, writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, '..');
const inFile = join(projectRoot, 'Shared', 'GenericBonuses.json');
const outFile = join(projectRoot, 'Mods', '7vs1', 'CoopZeroPop.SC2Mod', 'Base.SC2Data', 'LibE0EAE146_GenericBonusCatalog.galaxy');

const data = JSON.parse(readFileSync(inFile, 'utf8'));
const bonuses = data.bonuses;

// Map extra_call JSON spec to galaxy code line(s).
function extraCallToGalaxy(call, indent) {
  const pad = ' '.repeat(indent);
  switch (call.call) {
    case 'apply_kerrigan_creep_bonus':
      return [`${pad}libKPVP_gf_apply_kerrigan_creep_bonus(lp_player);`];
    case 'allow_ability':
      return [`${pad}libE0EAE146_gf_AllowAbilityIfPresent(lp_player, "${call.abil}", ${call.cmd});`];
    case 'enable_biomass':
      return [`${pad}libE0EAE146_gf_EnableAbathurBiomassForGenericBonus(lp_player, "${call.unit_type}");`];
    default:
      throw new Error(`Unknown extra_call type: ${call.call}`);
  }
}

let sb = '';
sb += '// Auto-generated by build-generic-bonus-catalog.mjs. DO NOT EDIT.\n';
sb += '// Source: Shared/GenericBonuses.json\n';
sb += '// Provides data-driven bonus->upgrade mapping for GenericBonusApplyPassives().\n\n';

// gf_GenericBonusUpgradeCount: returns number of upgrades for a bonus
sb += 'int libE0EAE146_gf_GenericBonusUpgradeCount (string lp_bonusId) {\n';
for (const b of bonuses) {
  const count = (b.upgrades || []).length;
  if (count === 0) continue;
  sb += `    if (lp_bonusId == "${b.id}") { return ${count}; }\n`;
}
sb += '    return 0;\n';
sb += '}\n\n';

// gf_GenericBonusUpgrade: returns upgrade ID by index
sb += 'string libE0EAE146_gf_GenericBonusUpgrade (string lp_bonusId, int lp_index) {\n';
for (const b of bonuses) {
  const ups = b.upgrades || [];
  if (ups.length === 0) continue;
  sb += `    if (lp_bonusId == "${b.id}") {\n`;
  ups.forEach((u, i) => {
    sb += `        if (lp_index == ${i}) { return "${u}"; }\n`;
  });
  sb += '    }\n';
}
sb += '    return "";\n';
sb += '}\n\n';

// gf_GenericBonusExtraCalls: dispatches extra calls for a bonus
sb += 'void libE0EAE146_gf_GenericBonusExtraCalls (int lp_player, string lp_bonusId) {\n';
let hasExtra = false;
for (const b of bonuses) {
  const calls = b.extra_calls || [];
  if (calls.length === 0) continue;
  sb += hasExtra ? '    else if' : '    if';
  hasExtra = true;
  sb += ` (lp_bonusId == "${b.id}") {\n`;
  for (const c of calls) {
    const lines = extraCallToGalaxy(c, 8);
    for (const line of lines) sb += line + '\n';
  }
  sb += '    }\n';
}
sb += '}\n\n';

// gf_ApplyAllGenericBonusPassives: iterates all bonuses, checks enabled/level, applies upgrades + extra calls
// For level-type: apply if level > 0
// For toggle-type: apply if enabled
sb += 'void libE0EAE146_gf_ApplyAllGenericBonusPassives (int lp_player) {\n';
sb += '    // Variable Declarations\n';
sb += '    int lv_i;\n';
sb += '    string lv_upgrade;\n';
sb += '    int lv_count;\n';
sb += '    int lv_level;\n\n';
sb += '    // Implementation\n';
for (const b of bonuses) {
  const ups = b.upgrades || [];
  const calls = b.extra_calls || [];
  if (ups.length === 0 && calls.length === 0) continue; // skip bonuses with no passives
  if (b.type === 'level') {
    sb += `    lv_level = libE0EAE146_gf_GenericBonusLevel("${b.id}");\n`;
    sb += `    if (lv_level > 0) {\n`;
  } else {
    sb += `    if (libE0EAE146_gf_GenericBonusEnabled("${b.id}")) {\n`;
  }
  if (ups.length > 0) {
    sb += `        lv_count = libE0EAE146_gf_GenericBonusUpgradeCount("${b.id}");\n`;
    sb += '        lv_i = 0;\n';
    sb += '        while (lv_i < lv_count) {\n';
    sb += `            lv_upgrade = libE0EAE146_gf_GenericBonusUpgrade("${b.id}", lv_i);\n`;
    sb += '            if (lv_upgrade != "") {\n';
    sb += '                libE0EAE146_gf_CommanderPowerSetUpgradeAtLeast(lp_player, lv_upgrade, 1);\n';
    sb += '            }\n';
    sb += '            lv_i += 1;\n';
    sb += '        }\n';
  }
  if (calls.length > 0) {
    sb += `        libE0EAE146_gf_GenericBonusExtraCalls(lp_player, "${b.id}");\n`;
  }
  sb += '    }\n';
}
sb += '}\n';

writeFileSync(outFile, sb, 'utf8');
console.log(`Generated ${outFile} (${bonuses.length} bonuses)`);
