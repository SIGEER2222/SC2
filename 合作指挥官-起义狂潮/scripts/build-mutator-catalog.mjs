// build-mutator-catalog.mjs
// Read Shared/Mutators/mutator-ids.json and generate LibE0EAE146_MutatorCatalog.galaxy.
// This galaxy module is the single source of truth for mutator index<->id and
// attribute_value<->id mappings, replacing the hardcoded lists in
// LibE0EAE146_MutatorRuntime.galaxy.
//
// Usage: node scripts/build-mutator-catalog.mjs

import { readFileSync, writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, '..');
const inFile = join(projectRoot, 'Shared', 'Mutators', 'mutator-ids.json');
const outFile = join(projectRoot, 'Mods', '7vs1', 'CoopZeroPop.SC2Mod', 'Base.SC2Data', 'LibE0EAE146_MutatorCatalog.galaxy');

const data = JSON.parse(readFileSync(inFile, 'utf8'));
const mutators = data.mutators;

// Validate: indices are contiguous 1..N
const indices = mutators.map(m => m.index);
for (let i = 0; i < mutators.length; i += 1) {
  if (indices[i] !== i + 1) {
    throw new Error(`mutator-ids.json: index ${i + 1} expected, got ${indices[i]} at position ${i}`);
  }
}
const ids = mutators.map(m => m.id);
const idCount = mutators.length;

// Mutators that have an attribute_value (used by attribute->id lookup).
const attrEntries = mutators.filter(m => m.attribute_value !== undefined && m.attribute_value !== null && m.attribute_value !== '');
const attrCount = attrEntries.length;

let sb = '';
sb += '// Auto-generated by build-mutator-catalog.mjs. DO NOT EDIT.\n';
sb += '// Source: Shared/Mutators/mutator-ids.json\n';
sb += '// Provides data-driven mutator index<->id and attribute_value<->id lookups,\n';
sb += '// replacing the hardcoded lists previously in LibE0EAE146_MutatorRuntime.galaxy.\n\n';

// --- Constants ---
sb += `const int libE0EAE146_gv_mutatorIdCount = ${idCount};\n`;
sb += `const int libE0EAE146_gv_mutatorAttributeCount = ${attrCount};\n\n`;

// --- Index -> ID lookup ---
// We expose gf_MutatorIdByIndex(int) and gf_MutatorIndexById(string) so the runtime
// can iterate without depending on array initializer syntax restrictions.
sb += 'string libE0EAE146_gf_MutatorIdByIndex (int lp_index) {\n';
for (const m of mutators) {
  sb += `    if (lp_index == ${m.index}) { return "${m.id}"; }\n`;
}
sb += '    return "";\n';
sb += '}\n\n';

// --- ID -> Index lookup ---
sb += 'int libE0EAE146_gf_MutatorIndexById (string lp_id) {\n';
for (const m of mutators) {
  sb += `    if (lp_id == "${m.id}") { return ${m.index}; }\n`;
}
sb += '    return -1;\n';
sb += '}\n\n';

// --- Attribute value -> ID lookup ---
// Only mutators that have an attribute_value are listed here.
sb += 'string libE0EAE146_gf_MutatorIdByAttribute (string lp_attributeValue) {\n';
for (const m of attrEntries) {
  sb += `    if (lp_attributeValue == "${m.attribute_value}") { return "${m.id}"; }\n`;
}
sb += '    return "";\n';
sb += '}\n';

writeFileSync(outFile, sb, 'utf8');
console.log(`Generated ${outFile} (${idCount} mutators, ${attrCount} with attribute_value)`);
