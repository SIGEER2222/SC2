// build-commander-registry.mjs
// Read Shared/Commanders/*.json and generate LibE0EAE146_CommanderRegistry.galaxy.
// This galaxy module provides data-driven dispatcher functions replacing the hardcoded
// if-else chains in LibE0EAE146.galaxy Initialize() and InitializeBase().
//
// Usage: node scripts/build-commander-registry.mjs

import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, '..');
const inDir = join(projectRoot, 'Shared', 'Commanders');
const outFile = join(projectRoot, 'Mods', '7vs1', 'CoopZeroPop.SC2Mod', 'Base.SC2Data', 'LibE0EAE146_CommanderRegistry.galaxy');

// Load all commander JSON files (skip _registry.json)
const files = readdirSync(inDir).filter(f => f.endsWith('.json') && f !== '_registry.json');
const commanders = [];
for (const f of files) {
  const data = JSON.parse(readFileSync(join(inDir, f), 'utf8'));
  commanders.push(data);
}

// Sort by runtime_name for stable output
commanders.sort((a, b) => a.runtime_name.localeCompare(b.runtime_name));

// Build name->condition map (include aliases). Each comparison wrapped in () to match
// galaxy compiler expectations (original code uses ((a==b) || (c==d)) style).
function cmdCondition(cmd) {
  const names = [cmd.runtime_name, ...(cmd.aliases || [])];
  if (names.length === 1) {
    return `(lp_commander == "${names[0]}")`;
  }
  return names.map(n => `(lp_commander == "${n}")`).join(' || ');
}

let sb = '';
sb += '// Auto-generated by build-commander-registry.mjs. DO NOT EDIT.\n';
sb += '// Source: Shared/Commanders/*.json\n';
sb += '// Replaces hardcoded if-else chains in LibE0EAE146.galaxy Initialize() and InitializeBase().\n\n';

// gf_CommanderConsoleSkin
sb += 'string libE0EAE146_gf_CommanderConsoleSkin (string lp_commander) {\n';
let first = true;
for (const c of commanders) {
  if (!c.console_skin) continue; // skip empty skin (Izsha)
  sb += first ? '    if' : '    else if';
  first = false;
  sb += ` (${cmdCondition(c)}) {\n`;
  sb += `        return "${c.console_skin}";\n`;
  sb += '    }\n';
}
sb += '    return "";\n';
sb += '}\n\n';

// gf_CommanderRuntimeInit
sb += 'void libE0EAE146_gf_CommanderRuntimeInit (int lp_player, string lp_commander, point lp_secondUnit, bool lp_createHero) {\n';
first = true;
for (const c of commanders) {
  if (!c.runtime_init) continue;
  sb += first ? '    if' : '    else if';
  first = false;
  sb += ` (${cmdCondition(c)}) {\n`;
  // Runtime checkpoints (Raynor/RaynorX)
  if (c.runtime_checkpoints && c.runtime_checkpoints.length > 0) {
    const before = c.runtime_checkpoints.find(x => x.includes('.before'));
    const after = c.runtime_checkpoints.find(x => x.includes('.after'));
    if (before) sb += `        libE0EAE146_gf_RuntimeCheckpoint("${before}");\n`;
    const libPrefix = c.runtime_init_lib === 'libE0EAE147' ? 'libE0EAE147' : 'libE0EAE146';
    sb += `        ${libPrefix}_gf_${c.runtime_init}(lp_player, lp_secondUnit, lp_createHero);\n`;
    if (after) sb += `        libE0EAE146_gf_RuntimeCheckpoint("${after}");\n`;
  } else {
    const libPrefix = c.runtime_init_lib === 'libE0EAE147' ? 'libE0EAE147' : 'libE0EAE146';
    sb += `        ${libPrefix}_gf_${c.runtime_init}(lp_player, lp_secondUnit, lp_createHero);\n`;
  }
  sb += '    }\n';
}
sb += '}\n\n';

// gf_CommanderApplySpecialInit
sb += 'void libE0EAE146_gf_CommanderApplySpecialInit (int lp_player, string lp_commander, bool lp_rpg) {\n';
first = true;
for (const c of commanders) {
  if (!c.special_init || c.special_init.length === 0) continue;
  sb += first ? '    if' : '    else if';
  first = false;
  sb += ` (${cmdCondition(c)}) {\n`;
  for (const s of c.special_init) {
    const lines = generateSpecialInit(s, c);
    for (const line of lines) {
      sb += `        ${line}\n`;
    }
  }
  sb += '    }\n';
}
sb += '}\n\n';

function generateSpecialInit(s, cmd) {
  const lines = [];
  let body = [];
  switch (s.type) {
    case 'add_supply':
      body.push(`PlayerModifyPropertyInt(lp_player, c_playerPropSuppliesLimit, c_playerPropOperAdd, ${s.amount});`);
      break;
    case 'init_veterancy':
      body.push('libC0F50AA6_gf_InitlizeMengskVeterancy();');
      break;
    case 'create_caster_unit':
      body.push(`libNtve_gf_CreateUnitsWithDefaultFacing(1, "${s.unit}", c_unitCreateIgnorePlacement, 1, RegionGetBoundsMin(RegionEntireMap()));`);
      body.push(`lib67C0F0E7_gf_CU_GPInit(1, "${s.gp_init_commander}", UnitLastCreated(), null);`);
      if (s.squad_init) {
        const sq = s.squad_init;
        body.push(`lib67C0F0E7_gf_TychusSquadInitTrigger(1, ${sq.hero_count}, "${sq.abil}", "${sq.tech_type}", "${sq.event_structure}", "${sq.event_main}");`);
      }
      break;
    default:
      body.push(`// Unknown special_init type: ${s.type}`);
  }
  if (s.rpg_only) {
    lines.push('if (lp_rpg == false) {');
    for (const b of body) lines.push('    ' + b);
    lines.push('}');
  } else {
    for (const b of body) lines.push(b);
  }
  return lines;
}

writeFileSync(outFile, sb, 'utf8');
console.log(`Generated ${outFile} (${commanders.length} commanders)`);
