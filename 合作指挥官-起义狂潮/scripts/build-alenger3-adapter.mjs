// build-alenger3-adapter.mjs
// Read Shared/Alenger3/adapter-data.json and generate LibA3ADAPTER_Catalog.galaxy.
// This galaxy module provides data-driven upgrade and build-allow lists for the
// Alenger3 commander adapter, replacing the hardcoded TechTreeUpgradeAddLevel and
// TechTreeAbilityAllow calls in LibA3ADAPTER.galaxy.
//
// Usage: node scripts/build-alenger3-adapter.mjs

import { readFileSync, writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, '..');
const inFile = join(projectRoot, 'Shared', 'Alenger3', 'adapter-data.json');
const outFile = join(projectRoot, 'Mods', '7vs1', 'Alenger3Adapter.SC2Mod', 'Base.SC2Data', 'LibA3ADAPTER_Catalog.galaxy');

const data = JSON.parse(readFileSync(inFile, 'utf8'));

let sb = '';
sb += '// Auto-generated by build-alenger3-adapter.mjs. DO NOT EDIT.\n';
sb += '// Source: Shared/Alenger3/adapter-data.json\n';
sb += '// Provides data-driven upgrade and build-allow lists for Alenger3 adapter.\n\n';

// Group upgrades by their "group" field (overload / standard).
const overloadUpgrades = data.upgrades.filter(u => u.group === 'overload');
const standardUpgrades = data.upgrades.filter(u => u.group === 'standard');

// --- Upgrade count constants ---
sb += `const int libA3ADAPTER_gv_overloadUpgradeCount = ${overloadUpgrades.length};\n`;
sb += `const int libA3ADAPTER_gv_standardUpgradeCount = ${standardUpgrades.length};\n`;
sb += `const int libA3ADAPTER_gv_buildAllowCount = ${data.build_allows.length};\n\n`;

// --- Overload upgrades (超标强制强度) ---
// We expose per-index accessors so the runtime can iterate without array globals.
sb += 'string libA3ADAPTER_gf_OverloadUpgradeId (int lp_index) {\n';
overloadUpgrades.forEach((u, i) => {
  sb += `    if (lp_index == ${i + 1}) { return "${u.id}"; }\n`;
});
sb += '    return "";\n';
sb += '}\n\n';

sb += 'int libA3ADAPTER_gf_OverloadUpgradeLevel (int lp_index) {\n';
overloadUpgrades.forEach((u, i) => {
  sb += `    if (lp_index == ${i + 1}) { return ${u.level}; }\n`;
});
sb += '    return 0;\n';
sb += '}\n\n';

// --- Standard upgrades (常规强制强度) ---
sb += 'string libA3ADAPTER_gf_StandardUpgradeId (int lp_index) {\n';
standardUpgrades.forEach((u, i) => {
  sb += `    if (lp_index == ${i + 1}) { return "${u.id}"; }\n`;
});
sb += '    return "";\n';
sb += '}\n\n';

sb += 'int libA3ADAPTER_gf_StandardUpgradeLevel (int lp_index) {\n';
standardUpgrades.forEach((u, i) => {
  sb += `    if (lp_index == ${i + 1}) { return ${u.level}; }\n`;
});
sb += '    return 0;\n';
sb += '}\n\n';

// --- Build allows (建造许可) ---
sb += 'string libA3ADAPTER_gf_BuildAllowAbil (int lp_index) {\n';
data.build_allows.forEach((b, i) => {
  sb += `    if (lp_index == ${i + 1}) { return "${b.abil}"; }\n`;
});
sb += '    return "";\n';
sb += '}\n\n';

sb += 'int libA3ADAPTER_gf_BuildAllowCmd (int lp_index) {\n';
data.build_allows.forEach((b, i) => {
  sb += `    if (lp_index == ${i + 1}) { return ${b.cmd}; }\n`;
});
sb += '    return -1;\n';
sb += '}\n';

writeFileSync(outFile, sb, 'utf8');
console.log(`Generated ${outFile} (${overloadUpgrades.length} overload + ${standardUpgrades.length} standard upgrades, ${data.build_allows.length} build allows)`);
