// build-map-metadata.mjs
// Read Shared/Maps/maps.json and generate LibE0EAE146_MapMetadata.galaxy.
// This galaxy module provides data-driven map metadata, replacing the hardcoded
// resource tables and special flags in LibE0EAE146.galaxy.
//
// Usage: node scripts/build-map-metadata.mjs

import { readFileSync, writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, '..');
const inFile = join(projectRoot, 'Shared', 'Maps', 'maps.json');
const outFile = join(projectRoot, 'Mods', '7vs1', 'CoopZeroPop.SC2Mod', 'Base.SC2Data', 'LibE0EAE146_MapMetadata.galaxy');

const data = JSON.parse(readFileSync(inFile, 'utf8'));
const maps = data.maps;

let sb = '';
sb += '// Auto-generated by build-map-metadata.mjs. DO NOT EDIT.\n';
sb += '// Source: Shared/Maps/maps.json\n';
sb += '// Provides data-driven map metadata replacing hardcoded tables in LibE0EAE146.galaxy.\n\n';

// gf_MapStartMinerals
sb += 'int libE0EAE146_gf_MapStartMinerals (string lp_mapId) {\n';
for (const m of maps) {
  if (m.minerals_difficulty) {
    const d = m.minerals_difficulty;
    sb += `    if (lp_mapId == "${m.map_id}") { return libNtve_gf_DifficultyValueInt(${d[0]}, ${d[1]}, ${d[2]}, ${d[3]}); }\n`;
  } else if (m.start_minerals !== undefined && m.start_minerals >= 0) {
    sb += `    if (lp_mapId == "${m.map_id}") { return ${m.start_minerals}; }\n`;
  }
}
sb += '    return -1;\n';
sb += '}\n\n';

// gf_MapStartVespene
sb += 'int libE0EAE146_gf_MapStartVespene (string lp_mapId) {\n';
for (const m of maps) {
  if (m.start_vespene !== undefined && m.start_vespene >= 0) {
    sb += `    if (lp_mapId == "${m.map_id}") { return ${m.start_vespene}; }\n`;
  }
}
sb += '    return -1;\n';
sb += '}\n\n';

// gf_MapStartSuppliesMade
sb += 'int libE0EAE146_gf_MapStartSuppliesMade (string lp_mapId) {\n';
for (const m of maps) {
  if (m.start_supplies !== undefined && m.start_supplies >= 0) {
    sb += `    if (lp_mapId == "${m.map_id}") { return ${m.start_supplies}; }\n`;
  }
}
sb += '    return -1;\n';
sb += '}\n\n';

// gf_MapNeedsPreInitializeRpg
sb += 'bool libE0EAE146_gf_MapNeedsPreInitializeRpg (string lp_mapId) {\n';
let hasPreInit = false;
for (const m of maps) {
  if (m.needs_pre_init_rpg) {
    sb += hasPreInit ? '    else if' : '    if';
    hasPreInit = true;
    sb += ` (lp_mapId == "${m.map_id}") {\n        return true;\n    }\n`;
  }
}
if (!hasPreInit) {
  // No maps need pre-init; emit a no-op that always returns false.
  // (Kept as an if-guard so the function body is valid even when empty.)
}
sb += '    return false;\n';
sb += '}\n\n';

// gf_MapNeedsUnitEventNullVariableInvalid
sb += 'bool libE0EAE146_gf_MapNeedsUnitEventNullVariableInvalid (string lp_mapId) {\n';
let hasNullInvalid = false;
for (const m of maps) {
  if (m.needs_unit_event_null) {
    sb += hasNullInvalid ? '    else if' : '    if';
    hasNullInvalid = true;
    sb += ` (lp_mapId == "${m.map_id}") {\n        return true;\n    }\n`;
  }
}
sb += '    return false;\n';
sb += '}\n\n';

// gf_MapUsesSharedPlayerCampaignAlly
sb += 'bool libE0EAE146_gf_MapUsesSharedPlayerCampaignAlly (string lp_mapId) {\n';
let hasSharedAlly = false;
for (const m of maps) {
  if (m.uses_shared_ally) {
    sb += hasSharedAlly ? '    else if' : '    if';
    hasSharedAlly = true;
    sb += ` (lp_mapId == "${m.map_id}") {\n        return true;\n    }\n`;
  }
}
sb += '    return false;\n';
sb += '}\n\n';

// gf_MapSecondUnitPoint: returns a map-specific second-unit point, or null if no override.
// The caller provides the base point (PlayerStartLocation) for polar offsets.
// point_id method ignores basePoint and returns a point by its preset ID.
sb += 'point libE0EAE146_gf_MapSecondUnitPoint (string lp_mapId, point lp_basePoint) {\n';
let hasSecondUnit = false;
for (const m of maps) {
  const o = m.second_unit_offset;
  if (!o) continue;
  sb += hasSecondUnit ? '    else if' : '    if';
  hasSecondUnit = true;
  sb += ` (lp_mapId == "${m.map_id}") {\n`;
  if (o.method === 'point_id') {
    sb += `        return PointFromId(${o.value});\n`;
  } else if (o.method === 'polar') {
    sb += `        return PointWithOffsetPolar(lp_basePoint, ${o.offset}, ${o.angle});\n`;
  }
  sb += '    }\n';
}
sb += '    return null;\n';
sb += '}\n';

writeFileSync(outFile, sb, 'utf8');
console.log(`Generated ${outFile} (${maps.length} maps)`);
